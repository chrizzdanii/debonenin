-- DEBONE Digital Hub - database schema for Supabase (Postgres)
-- Run this whole file once in Supabase: SQL Editor -> New query -> paste -> Run.
-- It is safe to run again later (it never deletes data).

create table if not exists users (
  id integer generated by default as identity primary key,
  name text,
  email text not null unique,
  pass text not null,
  bal integer not null default 0 check (bal >= 0),      -- a wallet can never go below zero
  active integer not null default 1,
  agreed_at timestamptz,
  created timestamptz default now(),
  totp_secret text,
  totp_on integer not null default 0,
  totp_last bigint not null default 0
);
create table if not exists tx (
  id integer generated by default as identity primary key,
  uid integer not null references users(id),
  svc text, amt integer, status text,
  at timestamptz default now()
);
create table if not exists pay (
  ref text primary key,
  uid integer not null references users(id),
  amt integer, charged integer, status text,
  at timestamptz default now()
);
create table if not exists reqs (
  id integer generated by default as identity primary key,
  uid integer not null references users(id),
  svc text, label text, ref text, price integer, status text, result text, input text,
  checked timestamptz,
  at timestamptz default now()
);
create table if not exists prices (
  k text primary key,
  price integer not null,
  cost integer not null default 0,
  active integer not null default 1
);
create table if not exists settings (k text primary key, v text);
create table if not exists admin_log (
  id integer generated by default as identity primary key,
  at timestamptz default now(),
  admin text, action text, detail text
);
create table if not exists results (
  id integer generated by default as identity primary key,
  at timestamptz default now(),
  uid integer, email text, svc text, label text, hint text, outcome text, price integer,
  pdf text, raw text, info text, photo text
);
create table if not exists transfers (
  id integer generated by default as identity primary key,
  ref text unique,
  uid integer not null references users(id),
  amt integer, credited integer, status text, reason text,
  proof bytea, proof_name text, proof_mime text, proof_hash text, decided_by text,
  at timestamptz default now(),
  upd timestamptz default now()
);
create table if not exists sess (sid text primary key, data text, exp bigint, uid integer);
create table if not exists rate (
  k text not null, win bigint not null, n integer not null,
  at timestamptz default now(),
  primary key (k, win)
);
create table if not exists locks (k text primary key, at timestamptz default now());

create index if not exists ix_tx on tx (uid, id);
create index if not exists ix_reqs on reqs (uid, status);
create index if not exists ix_pay on pay (status);
create index if not exists ix_pay_uid on pay (uid);
create index if not exists ix_transfers on transfers (status, uid);
create index if not exists ix_transfers_hash on transfers (proof_hash);
create index if not exists ix_sess_uid on sess (uid);
create index if not exists ix_results_at on results (at);

-- SECURITY: Supabase publishes every table in the "public" schema through a web API that anyone
-- with your project's public (anon) key can call. Row Level Security with NO policies means that
-- public API can read and change NOTHING. Only your server (which connects directly) can.
do $$
declare t text;
begin
  foreach t in array array['users','tx','pay','reqs','prices','settings','admin_log','results','transfers','sess','rate','locks'] loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon', t);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('revoke all on public.%I from authenticated', t);
    end if;
  end loop;
end $$;
